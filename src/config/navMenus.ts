export type NavItem = {
  name: string;
  menuCode: string;
  iconKey?: string | null;
  path?: string;
  subItems?: NavItem[];
};

function toNavigablePath(path?: string | null): string | undefined {
  const value = (path || "").trim();
  if (value === "" || value === "#") return undefined;
  return value.startsWith("/") ? value : `/${value}`;
}

/** Flatten every linkable path in a nav subtree (for active-state matching). */
export function collectNavPaths(item: NavItem): string[] {
  const own = item.path ? [item.path] : [];
  return own.concat(...(item.subItems || []).map(collectNavPaths));
}

/**
 * Build sidebar tree from flat menu rows (parent_id based, any depth).
 * Only rows with can_read and show_sidebar are rendered (legacy `menu_*` rows
 * without a React route are flagged show_sidebar = false); rows whose parent
 * is missing from the list are promoted to roots so they stay reachable.
 */
export function buildNavItems(menus: MenuPermission[]): NavItem[] {
  const visible = menus
    .filter((item) => item.can_read && item.show_sidebar !== false)
    .sort((a, b) => (a.sort_order ?? 0) - (b.sort_order ?? 0));

  const ids = new Set(visible.map((item) => item.menu_id));
  const byParent = new Map<number | null, MenuPermission[]>();
  for (const item of visible) {
    const parent = item.parent_id ?? null;
    const key = parent !== null && ids.has(parent) ? parent : null;
    const list = byParent.get(key) || [];
    list.push(item);
    byParent.set(key, list);
  }

  const build = (row: MenuPermission, seen: Set<number>): NavItem | null => {
    if (seen.has(row.menu_id)) return null;
    const nextSeen = new Set(seen).add(row.menu_id);

    const subItems = (byParent.get(row.menu_id) || [])
      .map((child) => build(child, nextSeen))
      .filter((child): child is NavItem => child !== null);
    const path = toNavigablePath(row.path || row.menu_url);

    if (subItems.length === 0 && !path) return null;

    return {
      name: row.menu_name,
      menuCode: row.menu_code,
      iconKey: row.icon,
      ...(subItems.length > 0 ? { subItems } : { path }),
    };
  };

  return (byParent.get(null) || [])
    .map((root) => build(root, new Set()))
    .filter((item): item is NavItem => item !== null);
}
